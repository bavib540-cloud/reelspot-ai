import { serve } from 'std/server'
import { createClient } from '@supabase/supabase-js'

const SUPA_URL = Deno.env.get('SUPABASE_URL')!
const SUPA_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!
const supabase = createClient(SUPA_URL, SUPA_KEY)

function buildPrompt(form: Record<string, any>) {
  return `
    You are a short-form video creative assistant for a filming location app.
    Create 3 original short-form video ideas in JSON format with:
    {"ideas":[{"title":"...","hook":"...","storyline":"...","locationCategory":"...","sound":"...","camera":"...","editing":"...","caption":"...","hashtags":"..."}]}

    Requirements:
    - genre: ${form.genre || 'Cinematic'}
    - duration: ${form.duration || 30}s
    - location: ${form.location || 'Marina Beach Access'}
    - people: ${form.people || 2}
    - equipment: ${form.equipment || 'phone only'}
    - mood: ${form.mood || 'cinematic'}
    - language: ${form.language || 'Tamil'}
    - Keep the output fully JSON and do not add markdown fences.
  `
}

async function generateWithOpenAI(form: Record<string, any>) {
  const apiKey = Deno.env.get('OPENAI_API_KEY')
  if (!apiKey) return null

  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model: 'gpt-4o-mini',
      temperature: 0.8,
      messages: [
        { role: 'system', content: 'You create vivid, platform-ready short-form video concepts.' },
        { role: 'user', content: buildPrompt(form) }
      ],
      response_format: { type: 'json_object' }
    })
  })

  if (!response.ok) {
    const text = await response.text()
    throw new Error(`OpenAI request failed: ${text}`)
  }

  const json = await response.json()
  const content = json.choices?.[0]?.message?.content
  if (!content) return null

  const parsed = JSON.parse(content)
  return parsed.ideas || null
}

serve(async (req) => {
  try {
    const authHeader = req.headers.get('authorization') || ''
    const token = authHeader.replace('Bearer ', '')
    if (!token) return new Response(JSON.stringify({ error: 'unauthenticated' }), { status: 401 })

    const { data: userData, error: userErr } = await supabase.auth.getUser(token)
    if (userErr || !userData?.user) return new Response(JSON.stringify({ error: 'invalid_token' }), { status: 401 })

    const userId = userData.user.id
    const body = await req.json()

    const { data: rpcData, error: rpcErr } = await supabase.rpc('consume_credit', { p_user: userId })
    if (rpcErr) {
      console.error('consume_credit error', rpcErr)
      return new Response(JSON.stringify({ error: 'credit_check_failed' }), { status: 402 })
    }
    if (rpcData === false) {
      return new Response(JSON.stringify({ error: 'no_credits_left' }), { status: 402 })
    }

    const ideas = await generateWithOpenAI(body)
    if (ideas && Array.isArray(ideas) && ideas.length > 0) {
      return new Response(JSON.stringify({ ideas, message: 'Generated by OpenAI via server-side API.' }), {
        headers: { 'Content-Type': 'application/json' }
      })
    }

    // Fallback: deterministic local concept generator to keep the product working even without an external AI API.
    const localIdeas = Array.from({ length: 3 }, (_, idx) => ({
      title: `Concept ${idx + 1}`,
      hook: 'A short-form story with a clean visual payoff and strong timing.',
      storyline: `A ${body.genre || 'Cinematic'} concept filmed at ${body.location || 'Marina Beach Access'} with a ${body.duration || 30}-second rhythm and ${body.equipment || 'phone only'} setup.`,
      locationCategory: body.location || 'Sample location',
      sound: body.mood || 'cinematic',
      camera: 'Slow push-in with a clean reveal',
      editing: 'Short cuts and a strong final beat',
      caption: `${body.language || 'Tamil'} storytelling energy`,
      hashtags: '#ReelSpotAI #ShortFormStory #CreatorLife'
    }))

    return new Response(JSON.stringify({ ideas: localIdeas, message: 'Generated via local fallback. Add OPENAI_API_KEY to enable server-side AI generation.' }), {
      headers: { 'Content-Type': 'application/json' }
    })
  } catch (err) {
    console.error(err)
    return new Response(JSON.stringify({ error: 'server_error' }), { status: 500 })
  }
})
